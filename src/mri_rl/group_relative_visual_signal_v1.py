def _diff(b, a):
    if isinstance(a, dict) and isinstance(b, dict):
        return {k: _diff(b[k], a[k]) for k in a if k in b and isinstance(a[k], (int, float, dict)) and not isinstance(a[k], bool)}
    return b - a if isinstance(a, (int, float)) and isinstance(b, (int, float)) else None


def analyze(arms):
    """arms: {'A'|'B': diag.rederive_arm(...) output}. Returns the PRIVATE report (contains opaque response keys only in row tables)."""
    rows = {(arm, seg): response_table(arms[arm][seg]['units'], segment=seg, arm=arm, origin=arms[arm][seg]['rollout_origin'])
            for arm in ('A', 'B') for seg in (0, 1)}
    exposure = matched_exposure(rows[('A', 0)], rows[('B', 0)])
    v0 = {arm: segment_view(rows[(arm, 0)]) for arm in ('A', 'B')}
    shared_rows = rows[('A', 0)]
    mri = [r for r in shared_rows if r['task'] == 'MRI']
    key_numbers = lambda v: {'admitted_groups': v['groups']['admitted_total'], 'allocation_total': v['allocation']['total'],
                             'allocation_by_task': v['allocation']['by_task'],
                             'label_indicator_projection_sequence': v['allocation']['label_indicator_projection']['sequence'],
                             'label_indicator_projection_per_token': v['allocation']['label_indicator_projection']['per_token']}
    report = {'schema': SCHEMA, 'status': 'EXECUTED_CPU_READ_ONLY', 'implemented_by': IMPLEMENTED_BY, 'boundaries': dict(BOUNDARIES), 'claims': dict(CLAIMS),
              'segment0_common32_matched': {'label': 'EXACT_MATCHED: same Parent Adam52 policy, identical 32 responses/tokens/images/rewards; only grouping differs',
                                            'exposure': exposure, 'arms': v0,
                                            'shared_block_anova': {v: anova(mri, v) for v in ('r', 'r_raw', 'correct', 'format')},
                                            'shared_block_anova_format_valid_only_correct': anova([r for r in mri if r['valid']], 'correct'),
                                            'shared_reward_component_ss': reward_component_ss(mri), 'shared_image_stats': image_stats(mri),
                                            'B_minus_A': _diff(key_numbers(v0['B']), key_numbers(v0['A']))},
              'segment1_own_policy_observational': {'label': 'OBSERVATIONAL: A and B segment-1 rollouts come from DIFFERENT post-update policies; never mixed or matched',
                                                    'arms': {arm: segment_view(rows[(arm, 1)]) for arm in ('A', 'B')}},
              'rows_PRIVATE': {f'{arm}{seg}': v for (arm, seg), v in rows.items()}}
    return report


# ================================================================ public aggregate
DROP_PUBLIC = frozenset({'key', 'rows_PRIVATE', 'images', 'group_stats'})
# Case/group-level identifiers or indices that must never appear as a public key (recursive), plus any per-case/per-group list.
PUBLIC_CASE_KEYS = frozenset({'unit', 'group', 'key', 'context', 'contexts', 'id', 'index', 'segment', 'response_id', 'group_stats', 'images',
                              'correct_by_image'})


def _strip(node):
    if isinstance(node, dict):
        return {k: _strip(v) for k, v in node.items() if k not in DROP_PUBLIC}
    if isinstance(node, list):
        return [_strip(v) for v in node]
    return node


def public_case_key_check(public):
    """Recursive regression: rejects case/group keys and ANY list of dicts (per-case or per-group records) in a public aggregate."""
    hits = []

    def walk(node, path):
        if isinstance(node, dict):
            for k, v in node.items():
                if k in PUBLIC_CASE_KEYS:
                    hits.append(path + '.' + k)
                walk(v, path + '.' + k)
        elif isinstance(node, (list, tuple)):
            if any(isinstance(v, (dict, list, tuple)) for v in node):
                hits.append(path + '[]')
            for i, v in enumerate(node):
                walk(v, f'{path}[{i}]')
    walk(public, '')
    require(not hits, 'Public aggregate carries case/group-level keys or per-record lists: ' + ','.join(sorted(hits)[:8]))
    return {'case_keys_checked': len(PUBLIC_CASE_KEYS), 'per_record_lists': 0, 'status': 'PASS'}


def public_aggregate(report):
    pub = _strip({k: v for k, v in report.items() if k != 'rows_PRIVATE'})
    pub['schema'] = SCHEMA + '-aggregate'
    pub['public_case_keys'] = public_case_key_check(pub)
    pub['public_schema'] = diag.public_schema_check(pub)
    return pub


# ================================================================ orchestration over the real immutable run (root executes)
def run(*, root, worktree, run_dir, out_dir, results_path, expected_scope_sha256=None, regrade=True):
    install_import_guard()
    ctx = diag.authenticate(root=root, worktree=worktree, run_dir=run_dir, results_path=results_path, expected_scope_sha256=expected_scope_sha256)
    run_dir, root = ctx['run_dir'], Path(root).resolve()
    out_dir = Path(out_dir).resolve()
    require(out_dir.is_relative_to(root / 'local_data') and not out_dir.is_relative_to(run_dir), 'Output must be under local_data, outside the immutable run')
    targets = [out_dir / n for n in ('group_relative_visual_signal_PRIVATE.json', 'group_relative_visual_signal_AGGREGATE_PUBLIC_CANDIDATE.json')]
    require(not any(p.exists() for p in targets), 'Refusing to overwrite an existing analysis output')
    for arm in ('A', 'B'):
        r0 = ctx['receipts'][(arm, 0)]
        require(r0['adam_step_before'] == 52 and r0['rollout_origin'] == 'COMMON_PARENT', 'Segment 0 must start at the Parent Adam52 common rollout')
    grader, regrade_status = None, 'NOT_REQUESTED'
    if regrade:
        try:
            from mri_rl.two_task_training import make_grader
            grader = make_grader(diag.load_json(ctx['runtime']['calibration']))
            regrade_status = 'PRODUCTION_GRADER'
        except ImportError as error:
            regrade_status = 'NOT_VERIFIED: ' + type(error).__name__
    arms = {arm: diag.rederive_arm(ctx['units'], ctx['common_dir'], run_dir / f'stage{arm}_PRIVATE' / 'arm_PRIVATE', arm,
                                   reward_sha=ctx['reward_sha'], parent_receipt=ctx['parent_receipt'], grader=grader) for arm in ('A', 'B')}
    for arm in ('A', 'B'):
        for seg in (0, 1):
            require(arms[arm][seg]['saved_evidence_all_match'], f'{arm}{seg}: re-derived plan differs from the saved gradient evidence')
    report = analyze(arms)
    report['authentication'] = {k: ctx['record'][k] for k in ('scope_file_sha256', 'spec_sha256', 'parent_adapter_sha256', 'reward_calibration_sha256',
                                                              'prompt_condition', 'segment_receipts')}
    report['parent'] = {'adam_step': 52, 'common_parent_state_bound': True, 'segment0_receipts_start_at_common_parent': True}
    report['regrade_status'] = regrade_status
    public = public_aggregate(report)
    public['privacy'] = report['privacy'] = diag.privacy_check(public, diag._forbidden_values(ctx))
    loaded = forbidden_modules_loaded()
    require(not loaded, 'Forbidden module imported during analysis: ' + ','.join(loaded))
    reauth = diag.authenticate(root=root, worktree=worktree, run_dir=run_dir, results_path=results_path, expected_scope_sha256=expected_scope_sha256)
    report['inputs_unchanged_after_analysis'] = public['inputs_unchanged_after_analysis'] = reauth['record'] == ctx['record']
    out_dir.mkdir(parents=True, exist_ok=True)
    written = {p.name: diag.write_exclusive(p, v) for p, v in zip(targets, (report, public))}
    return {'written_sha256': written, 'public': public}
