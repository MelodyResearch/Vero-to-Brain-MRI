import time
from mri_rl import shared_rollout_gspo_core_v1 as shared
from mri_rl import paired_prompt_groups_v1 as ppg
from mri_rl.paired_prompt_groups_v1 import identity, canonical

STATUS = 'IMPLEMENTED_CPU_NOT_NATIVE_QUALIFIED'
EXPERIMENT = 'MULTISTEP_ON_POLICY_VERO_GSPO_AB'
SEQ_KIND, DALLAS_KIND = 'SEQ_PAIR', 'DALLAS_BLOCK'
SEQ_TASK, DALLAS_TASK = 'mri_sequence', 'mri_visit_correspondence'
CHARGEABLE = shared.CHARGEABLE
MAX_TOKENS, GROUP_SIZE, RESPONSES = shared.MAX_TOKENS, shared.GROUP_SIZE, shared.RESPONSES
WEIGHT = 1 / RESPONSES
require = shared.require
KEEP_SECONDS = 5400


class GuardStop(RuntimeError):
    """Finite HOLD at a safe unit boundary (power/memory/thermal/disk/wall guards). Never mid-unit."""


# ---------------------------------------------------------------- units / budget
def make_units(plan):
    units = []
    for r in plan['rounds']:
        for b in r['blocks']:
            if b['kind'] == SEQ_KIND:
                by = {row['reward_model']['ground_truth']: row for row in b['rows']}
                require(set(by) == {'FLAIR', 'contrast-enhanced T1'} and len(b['rows']) == 2, 'A SEQ_PAIR block holds exactly one FLAIR and one T1 row')
                require(len({row['extra_info']['patient_key'] for row in b['rows']}) == 1, 'A pair block is one patient')
                contexts = [{'key': 'F', 'row': by['FLAIR']}, {'key': 'T', 'row': by['contrast-enhanced T1']}]
            else:
                require(b['kind'] == DALLAS_KIND and len(b['rows']) == 2, 'DALLAS_BLOCK holds exactly two rows')
                contexts = [{'key': 'D1', 'row': b['rows'][0]}, {'key': 'D2', 'row': b['rows'][1]}]
            units.append({'index': len(units), 'round': r['round'], 'kind': b['kind'], 'contexts': contexts})
    return units


def unit_worst_case(unit, prompt_lengths, *, common=False):
    """Exact worst-case chargeable API endpoints for ONE unit (8 responses). `common`: generation/own-old are inherited, not charged."""
    P = max(prompt_lengths[c['row']['ability']] for c in unit['contexts'])
    n = RESPONSES
    positions = n * (P + MAX_TOKENS - 1)
    w = {'generated_response_tokens': n * MAX_TOKENS, 'sampler_draws': n * (MAX_TOKENS + 1), 'generation_language_model_calls': n * (MAX_TOKENS + 4),
         'generation_vision_embedding_calls': n, 'detached_old_forwards': n, 'gradient_forwards': n, 'backward_calls': n,
         'scorer_vision_embedding_calls': 2 * n, 'scorer_language_model_calls': 2 * n, 'teacherforced_input_positions': 2 * positions, 'optimizer_updates': 1}
    if common:
        for key in ('generated_response_tokens', 'sampler_draws', 'generation_language_model_calls', 'generation_vision_embedding_calls', 'detached_old_forwards'):
            w[key] = 0
        w['scorer_vision_embedding_calls'] = w['scorer_language_model_calls'] = n
        w['teacherforced_input_positions'] = positions
    return w


def common_rollout_budget(unit, prompt_lengths):
    n = RESPONSES
    P = max(prompt_lengths[c['row']['ability']] for c in unit['contexts'])
    return {'generated_response_tokens': n * MAX_TOKENS, 'sampler_draws': n * (MAX_TOKENS + 1), 'generation_language_model_calls': n * (MAX_TOKENS + 4),
            'generation_vision_embedding_calls': n, 'detached_old_forwards': n, 'gradient_forwards': 0, 'backward_calls': 0, 'scorer_vision_embedding_calls': n,
            'scorer_language_model_calls': n, 'teacherforced_input_positions': n * (P + MAX_TOKENS - 1), 'optimizer_updates': 0}


def derive_arm_budget(units, prompt_lengths, *, maximum_seconds=KEEP_SECONDS, common_first_unit=True):
    require(units and len(units) % 2 == 0 and [u['kind'] for u in units] == [SEQ_KIND, DALLAS_KIND] * (len(units) // 2),
            'Only WHOLE rounds (SEQ_PAIR then DALLAS_BLOCK) are budgetable: a cap may not split a patient pair from its round')
    require(set(prompt_lengths) == {SEQ_TASK, DALLAS_TASK} and all(type(v) is int and 0 < v <= 2048 for v in prompt_lengths.values()), 'Measured expanded prompt lengths required')
    limits = {k: 0 for k in CHARGEABLE}
    for u in units:
        for k, v in unit_worst_case(u, prompt_lengths, common=(common_first_unit and u['index'] == 0)).items():
            limits[k] += v
    return {'experiment': EXPERIMENT, 'units': len(units), 'rounds': len(units) // 2, 'optimizer_updates': limits['optimizer_updates'],
            'generated_response_tokens': limits['generated_response_tokens'], 'prompt_lengths': dict(prompt_lengths), 'maximum_seconds': maximum_seconds,
            'limits': limits, 'common_rollout': common_rollout_budget(units[0], prompt_lengths), 'weight_per_admitted_response': WEIGHT,
            'common_first_unit': common_first_unit, 'claimed_cap_splits_pair': False, 'automatic_retry': False, 'unused_budget_transfer': False, 'extension_by_dev_score': False,
            'counting': 'Completed API endpoints (not kernels). Unit 0 generation/own-old is the ONE common rollout, charged to common_rollout only.'}


# ---------------------------------------------------------------- blocks
@dataclass(frozen=True)
class DContext:
    context_id: str
    pair_id: str
    modality: str
    prompt_sha256: str
    image_sha256: str
    checkpoint_sha256: str
    policy_sha256: str
    reward_policy_sha256: str

    @property
    def sha256(self):
        return identity(asdict(self))


@dataclass(frozen=True)
class UnitBlock:
    kind: str
    raw: dict
    responses: tuple
    sha256: str
    policy_sha256: str
    bundle: object = None


def _stream_ok(item, eos):
    shared._validate_stream(item, eos)


def build_block(unit, rollout, *, policy_sha, reward_policy_sha256, checkpoint_receipt_sha256=None):
    """Validate the backend's rollout for this unit and bind every response to its own context + the generating policy."""
    require(rollout.get('policy_sha256') == policy_sha, 'Rollout policy identity differs from the generating policy')
    receipt = checkpoint_receipt_sha256 or identity({'policy': policy_sha})
    keys = [c['key'] for c in unit['contexts']]
    require(set(rollout['contexts']) == set(keys) and len(rollout['responses']) == RESPONSES, 'Exactly the unit contexts and eight responses required')
    if unit['kind'] == SEQ_KIND:
        pair = identity({'patient_key': unit['contexts'][0]['row']['extra_info']['patient_key'], 'level': unit['contexts'][0]['row']['extra_info'].get('level')})
        contexts = {k: {**rollout['contexts'][k], 'row_id': c['row']['id'], 'pair_id': pair, 'checkpoint_sha256': policy_sha, 'policy_sha256': identity(shared.POLICY),
                        'reward_policy_sha256': reward_policy_sha256} for k, c in zip(keys, unit['contexts'])}
        items = [{k: v for k, v in r.items() if k in ('response_id', 'text', 'token_ids', 'raw_selected_logps', 'finish_reason', 'EOS_coverage', 'generation_tokens', 'grade')}
                 for r in sorted(rollout['responses'], key=lambda r: shared.RESPONSE_IDS.index(r['response_id']))]
        frozen = shared.freeze_bundle(parent={'receipt_sha256': receipt, 'adapter_sha256': policy_sha}, contexts=contexts, responses=items,
                                      effective_eos_ids=rollout['effective_eos_ids'])
        bundle = shared.load_bundle(frozen)
        return UnitBlock(SEQ_KIND, frozen, bundle.responses, bundle.sha256, policy_sha, bundle)
    require(unit['kind'] == DALLAS_KIND, 'Unknown unit kind')
    order = [f'{k}_{i}' for k in keys for i in range(GROUP_SIZE)]
    by_id = {r['response_id']: r for r in rollout['responses']}
    require(set(by_id) == set(order), 'Dallas response inventory must be D1_0..D1_3,D2_0..D2_3')
    contexts, responses, serial = {}, [], []
    for k, c in zip(keys, unit['contexts']):
        rec = rollout['contexts'][k]
        require(all(shared.sha(rec.get(f)) for f in ('prompt_text_sha256', 'image_sha256', 'rendered_prompt_token_ids_sha256', 'input_fingerprints_sha256')) and
                type(rec.get('prompt_length')) is int and 0 < rec['prompt_length'] <= 2048, 'Dallas context fingerprints required')
        ctx = DContext(c['row']['id'], identity({'dallas_row': c['row']['id']}), 'D', rec['prompt_text_sha256'], rec['image_sha256'], policy_sha, identity(shared.POLICY), reward_policy_sha256)
        contexts[k] = {**rec, 'context_sha256': ctx.sha256, 'row_id': c['row']['id']}
        for i in range(GROUP_SIZE):
            item = by_id[f'{k}_{i}']
            _stream_ok(item, rollout['effective_eos_ids'][k])
            grade = shared._grade_dict(item['grade'])
            g = ppg.Grade(accuracy=grade['accuracy'], format=grade['format'], total=grade['total'], overlong=grade['overlong'], raw_accuracy=grade['raw_accuracy'])
            token_sha, logps_sha = identity(tuple(item['token_ids'])), identity(item['raw_selected_logps'])
            text_sha = hashlib.sha256(item['text'].encode()).hexdigest()
            rr = shared.reward_receipt(item['response_id'], ctx.sha256, token_sha, text_sha, logps_sha, grade)
            responses.append(ppg.Response(item['response_id'], ctx, tuple(item['token_ids']), tuple(float(v) for v in item['raw_selected_logps']), g, rr))
            serial.append({'response_id': item['response_id'], 'context_key': k, 'text': item['text'], 'token_ids': list(item['token_ids']),
                           'raw_selected_logps': list(item['raw_selected_logps']), 'grade': grade, 'reward_receipt_sha256': rr})
    body = {'schema': 'multistep-dallas-block-v1', 'experiment': EXPERIMENT, 'policy_sha256': policy_sha, 'contexts': contexts, 'responses': serial}
    return UnitBlock(DALLAS_KIND, {**body, 'bundle_sha256': identity(body)}, tuple(responses), identity(body), policy_sha, None)


def arm_plan_for(block, arm):
    require(arm in shared.ARMS, 'Arm A or B required')
    if block.kind == SEQ_KIND:
        return shared.arm_plan(block.bundle, arm)             # existing grouping + 1/8 weights + inherited Adam60 gate
    items, effective, variable = [], 0, 0
    for number in range(2):
        group = block.responses[number * GROUP_SIZE:(number + 1) * GROUP_SIZE]
        require(len({r.context.context_id for r in group}) == 1, 'Dallas group must be one input context (unchanged same-prompt K4)')
        grades = [asdict(r.grade) for r in group]
        admitted = ppg.inherited_Adam60_gate(grades)
        effective += int(admitted)
        rewards = [r.grade.total for r in group]
        variable += int(max(rewards) - min(rewards) > 1e-12)
        for r, a in zip(group, ppg.advantages_from_rewards(rewards)):
            items.append(ppg.WeightedResponse(r, number, a, admitted, WEIGHT if admitted else 0.))
    plan = ppg.Plan('same_prompt', tuple(items), effective, variable)
    admitted_ids = tuple(i.response.response_id for i in items if i.weight > 0)
    return shared.ArmPlan(arm, plan, effective, admitted_ids, len(admitted_ids))


def check_old(block, old):
    require(isinstance(old, dict) and set(old) == {r.response_id for r in block.responses}, 'Own-old inventory must be exactly the eight responses')
    for r in block.responses:
        shared.selected_logp_parity(list(r.previous_logps), old[r.response_id])
    return True


def ownership(rollout_policy_sha, current_policy_sha):
    require(rollout_policy_sha == current_policy_sha, 'Rollout policy differs from this arm\'s current policy: off-policy / cross-arm rollout rejected')


# ---------------------------------------------------------------- the single common rollout
@dataclass(frozen=True)
class Common:
    block: UnitBlock
    old: dict
    parent_policy_sha256: str
    rng_dir: Path
    ledger: dict
    parent_state: dict = None        # {'policy','adam','rng'}: full trusted parent identity (R0)
    rng_after_digest: str = None     # R1

    @property
    def bundle(self):
        return self.block


def make_common_rollout(unit, backend, budget, *, prompt_lengths, reward_policy_sha256, output, checkpoint_receipt_sha256=None):
    """ONE F4+T4 generation from the common parent, plus its own-old logps (computed at that same parent). Never regenerated."""
    require(unit['index'] == 0 and unit['kind'] == SEQ_KIND, 'Only the first SEQ_PAIR unit may be the common rollout')
    output = Path(output)
    output.mkdir(parents=True, exist_ok=False)
    limits = budget['common_rollout']
    counters = shared.Counters(limits, None, lambda used: shared.replace_atomic(output / 'common_counters_PRIVATE.json', {'limits': limits, 'used': used}))
    if hasattr(backend, 'counters'):
        backend.counters = counters
    policy, adam = backend.policy_sha(), backend.adam_digest()
    rng0 = backend.rng_digest()
    parent_state = {'policy': policy, 'adam': adam, 'rng': rng0}
    raw = backend.generate(unit, prompt_lengths)
    require(backend.adam_digest() == adam and backend.policy_sha() == policy, 'Common rollout changed weights or Adam')
    rng1 = backend.rng_digest()
    require(rng1 != rng0, 'Common rollout did not consume RNG')
    rng_dir = output / 'rng_after_common'
    rng_dir.mkdir()
    backend.save_rng(rng_dir)
    block = build_block(unit, raw, policy_sha=policy, reward_policy_sha256=reward_policy_sha256, checkpoint_receipt_sha256=checkpoint_receipt_sha256)
    old = backend.score_old(unit, block.responses)
    check_old(block, old)
    require(backend.adam_digest() == adam and backend.policy_sha() == policy and backend.rng_digest() == rng1,
            'Own-old scoring changed weights, Adam or the post-generation RNG R1')
    shared.publish_once(output / 'common_bundle_PRIVATE.json', block.raw)
    shared.publish_once(output / 'common_old_PRIVATE.json', {'bundle_sha256': block.sha256, 'old': old, 'parent_state': parent_state, 'rng_after_digest': rng1})
    return Common(block, old, policy, rng_dir, counters.snapshot(), parent_state, rng1)


# ---------------------------------------------------------------- abandonment of an unfinished unit
def _read(path):
    return json.loads(Path(path).read_text())


def abandon_incomplete_unit(arm_dir, *, reason):
    """Human-recorded abandonment: the unit's FULL reserved cost is charged (no free retry); state is the last committed checkpoint."""
    arm_dir = Path(arm_dir)
    open_ones = [p for p in sorted(arm_dir.glob('reservation_unit_*.json')) if not (arm_dir / ('unit_' + p.stem.split('_')[-1])).exists()]
    require(len(open_ones) == 1, 'Exactly one incomplete reservation expected')
    res = _read(open_ones[0])
    counters_path = arm_dir / 'counters.json'
    saved = _read(counters_path)
    used = {k: max(saved['used'][k], res['counters_at_start'][k] + res['worst_case'][k]) for k in CHARGEABLE}
    require(all(used[k] <= saved['limits'][k] for k in CHARGEABLE), 'Abandoned unit would exceed the frozen limits')
    shared.replace_atomic(counters_path, {**saved, 'used': used})
    shared.publish_once(arm_dir / f"abandoned_unit_{res['unit']:04d}_{time.time_ns()}.json", {'reason': reason, 'charged_full_worst_case': True, 'reservation': res})
    os.unlink(open_ones[0])
    shared.sync_dir(arm_dir)
    return res['unit']


# ---------------------------------------------------------------- per-arm runner
class ArmRunner:
    def __init__(self, *, arm, units, backend, output, budget, prompt_lengths, reward_policy_sha256, common=None, guards=None, resume=False,
                 parent_policy_sha256=None, clock=time.monotonic):
        require(arm in shared.ARMS, 'Arm A or B required')
        require(budget == derive_arm_budget(units, prompt_lengths, maximum_seconds=budget.get('maximum_seconds', KEEP_SECONDS), common_first_unit=budget.get('common_first_unit', True)),
                'Budget is not the exact derived budget for these units')
        require(budget['common_first_unit'] == (common is not None), 'Budget and common-rollout declaration differ')
        self.arm, self.units, self.backend, self.budget, self.lengths = arm, units, backend, budget, prompt_lengths
        self.reward, self.common, self.guards, self.clock = reward_policy_sha256, common, guards or (lambda phase, info: None), clock
        self.output = Path(output)
        self.started = clock()
        self.committed = []
        if self.output.exists() and not resume:
            raise FileExistsError('Existing arm run requires explicit resume; preserve evidence')
        require(not resume or self.output.is_dir(), 'Missing arm run for resume')
        self.output.mkdir(parents=True, exist_ok=True)
        limits = budget['limits']
        path = self.output / 'counters.json'
        persist = lambda used: shared.replace_atomic(path, {'limits': limits, 'used': used})
        self._restore_state(resume, parent_policy_sha256, persist, path, limits)
        if hasattr(backend, 'counters'):
            backend.counters = self.counters

    # ---- state restoration / consistency
    def _unit_dirs(self):
        return sorted(p for p in self.output.glob('unit_*') if p.is_dir() and p.name[5:].isdigit())

    def _restore_state(self, resume, parent_policy_sha256, persist, path, limits):
        dirs = self._unit_dirs()
        for d in self.output.glob('reservation_unit_*.json'):
            k = d.stem.split('_')[-1]
            if not (self.output / f'unit_{k}').exists():
                raise RuntimeError(f'INCOMPLETE_UNIT_{k}: reserved unit has no committed checkpoint; no automatic retry (human abandonment required)')
        for number, d in enumerate(dirs):
            require(d.name == f'unit_{number:04d}' and (d / 'receipt_PRIVATE.json').is_file(), 'Committed unit inventory is not a contiguous receipted prefix')
            self.committed.append(_read(d / 'receipt_PRIVATE.json'))
        previous = None
        for rec in self.committed:
            require(rec['prev_receipt_sha256'] == previous, 'Receipt hash chain broken')
            previous = identity({k: v for k, v in rec.items() if k != 'receipt_sha256'})
            require(rec['receipt_sha256'] == previous, 'Receipt hash differs')
        self.last_receipt_sha = previous
        if self.committed:
            self.backend.load_checkpoint(dirs[-1])
            last = self.committed[-1]
            require(self.backend.policy_sha() == last['policy_sha_after'] and self.backend.adam_digest() == last['adam_digest_after'] and
                    self.backend.rng_digest() == last['rng_digest_after'], 'Restored weights/Adam/RNG differ from the last committed receipt')
            self.parent_policy_sha256 = _read(self.output / 'start_PRIVATE.json')['parent_policy_sha256']
        else:
            start = self.output / 'start_PRIVATE.json'
            if start.exists():
                require(resume, 'Unexpected start record without resume')
                rec = _read(start)
                require(self.backend.policy_sha() == rec['parent_policy_sha256'] and self.backend.adam_digest() == rec['adam_digest'] and
                        self.backend.rng_digest() == rec['rng_digest'], 'Backend is not at the recorded parent state')
                self.parent_policy_sha256 = rec['parent_policy_sha256']
            else:
                if parent_policy_sha256 is not None:
                    require(self.backend.policy_sha() == parent_policy_sha256, 'Backend must start from the common parent, not another arm\'s state')
                if self.common is not None:
                    ps = self.common.parent_state
                    require(ps is not None and (self.backend.policy_sha(), self.backend.adam_digest(), self.backend.rng_digest()) == (ps['policy'], ps['adam'], ps['rng']),
                            'Arm start (parameters+Adam+R0) differs from the trusted common parent state')
                self.parent_policy_sha256 = self.backend.policy_sha()
                shared.publish_once(start, {'parent_policy_sha256': self.parent_policy_sha256, 'adam_digest': self.backend.adam_digest(),
                                            'rng_digest': self.backend.rng_digest(), 'arm': self.arm})
        if path.exists():
            saved = _read(path)
            require(saved['limits'] == limits, 'Counter journal belongs to a different budget')
            self.counters = shared.Counters(limits, saved['used'], persist)
        else:
            self.counters = shared.Counters(limits, None, persist)
            persist(self.counters.snapshot())

    # ---- public inspection
    def receipts(self):
        return list(self.committed)

    def cursor(self):
        n = len(self.committed)
        return {'next_unit': n, 'complete': n == len(self.units), 'updates': sum(bool(r['updated']) for r in self.committed),
                'last_receipt_sha256': self.last_receipt_sha}

    # ---- execution
    def run(self):
        self.run_units(len(self.units) - len(self.committed))
        summary = self.safe_summary()
        shared.replace_atomic(self.output / 'complete_SAFE.json', summary)
        return summary

    def run_units(self, count):
        for _ in range(count):
            k = len(self.committed)
            if k >= len(self.units):
                break
            if self.clock() - self.started >= self.budget['maximum_seconds']:
                raise GuardStop('WALL_BUDGET_REACHED at a unit boundary')
            self._run_unit(self.units[k])

    def inject_rollout_for_test(self, unit, raw):
        ownership(raw['policy_sha256'], self.backend.policy_sha())

    def inject_common_for_test(self, unit):
        require(unit['index'] == 0, 'The common rollout may only be consumed by unit 0')

    def _check_common(self, unit):
        require(self.common is not None and unit['index'] == 0, 'The common rollout may only be consumed by unit 0')
        require(self.backend.policy_sha() == self.common.parent_policy_sha256 == self.parent_policy_sha256, 'Arm is not at the common parent: the shared rollout is no longer on-policy')
        parent = self.common.parent_state
        require(parent is not None and
                (self.backend.policy_sha(), self.backend.adam_digest(), self.backend.rng_digest()) ==
                (parent['policy'], parent['adam'], parent['rng']),
                'Common rollout use requires the trusted complete parent parameters, Adam and R0')

    def _run_unit(self, unit):
        k = unit['index']
        use_common = self.common is not None and k == 0
        self.guards('before_unit', {'unit': k, 'arm': self.arm})
        worst = unit_worst_case(unit, self.lengths, common=use_common)
        used0 = self.counters.snapshot()
        require(all(used0[x] + worst[x] <= self.counters.limits[x] for x in CHARGEABLE), 'Frozen unit budget cannot absorb this unit')
        if use_common:
            self._check_common(unit)
        policy_before, adam_before, rng_before = self.backend.policy_sha(), self.backend.adam_digest(), self.backend.rng_digest()
        reservation = {'unit': k, 'arm': self.arm, 'worst_case': worst, 'counters_at_start': used0, 'policy_sha_before': policy_before,
                       'adam_digest_before': adam_before, 'rng_digest_before': rng_before}
        shared.publish_once(self.output / f'reservation_unit_{k:04d}.json', reservation)
        snapshot = self.backend.snapshot()
        try:
            state = lambda: (self.backend.policy_sha(), self.backend.adam_digest(), self.backend.rng_digest())
            if use_common:
                block, own_old, origin = self.common.block, self.common.old, 'COMMON_PARENT'
                post_gen = state()
            else:
                raw = self.backend.generate(unit, self.lengths)
                ownership(raw['policy_sha256'], policy_before)
                post_gen = state()
                require(post_gen[0] == policy_before and post_gen[1] == adam_before, 'Generation changed parameters or Adam')
                require(post_gen[2] != rng_before, 'Generation did not consume RNG')
                block = build_block(unit, raw, policy_sha=policy_before, reward_policy_sha256=self.reward, checkpoint_receipt_sha256=self.last_receipt_sha)
                own_old, origin = self.backend.score_old(unit, block.responses), 'OWN_POLICY'
                require(state() == post_gen, 'Own-old scoring mutated parameters, Adam or RNG')
                check_old(block, own_old)
            require(block.policy_sha256 == policy_before, 'Block policy differs from the arm policy before the update')
            planned = arm_plan_for(block, self.arm)
            gradient, evidence = self.backend.gradient(planned, own_old, unit)
            require(state() == post_gen, 'Backward mutated parameters, Adam or RNG')
            norm = float(evidence.get('gradient_l2', 0.)) if gradient is not None else 0.
            decision = shared.update_decision(planned, norm)
            require(evidence.get('backward_calls', 0) == planned.backward_calls_needed, 'Backward calls differ from admitted responses')
            self.guards('before_update', {'unit': k, 'arm': self.arm})
            require(state() == post_gen, 'State changed before the optimizer step')
            updated = False
            if decision['update']:
                self.counters.charge('optimizer_updates')
                self.backend.apply_update(gradient)
                updated = True
                after = state()
                require(after[2] == post_gen[2], 'Optimizer step changed the RNG')
                require(after[1] != post_gen[1] and after[0] != post_gen[0], 'Updated arm left parameters or Adam unchanged')
            else:
                require(state() == post_gen, 'No-update unit changed parameters, Adam or RNG')
            if use_common:      # explicit protocol step (never a repair): continue the stream from the persisted post-common-rollout R1
                self.backend.load_rng(self.common.rng_dir)
                require(self.backend.rng_digest() == self.common.rng_after_digest, 'Restored R1 differs from the persisted common-rollout R1')
            used1 = self.counters.snapshot()
            delta = {x: used1[x] - used0[x] for x in CHARGEABLE}
            require(all(delta[x] <= worst[x] for x in CHARGEABLE), 'Unit exceeded its own reserved budget (cost overrun)')
            receipt = self._commit(unit, block, planned, evidence, decision, updated, origin, policy_before, adam_before, delta, used1, own_old)
        except BaseException as error:
            if (self.output / f'unit_{k:04d}').exists():
                self._reload_committed()           # the directory rename IS the commit; whatever failed afterwards is not rolled back
            else:
                self.backend.restore(snapshot)
                require_same = (self.backend.policy_sha(), self.backend.adam_digest(), self.backend.rng_digest()) == (policy_before, adam_before, rng_before)
                shared.replace_atomic(self.output / f'STOP_unit_{k:04d}_{time.time_ns()}_PRIVATE.json',
                                      {'error_type': type(error).__name__, 'error': str(error), 'rolled_back_exactly': require_same, 'counters': self.counters.snapshot()})
            raise
        self.guards('after_commit', {'unit': k, 'arm': self.arm})
        return receipt

    def _reload_committed(self):
        self.committed = []
        for d in self._unit_dirs():
            self.committed.append(_read(d / 'receipt_PRIVATE.json'))
        self.last_receipt_sha = self.committed[-1]['receipt_sha256'] if self.committed else None

    def _commit(self, unit, block, planned, evidence, decision, updated, origin, policy_before, adam_before, delta, used, own_old):
        k = unit['index']
        grades = [r.grade for r in block.responses]
        groups = {}
        for item in planned.plan.items:
            groups.setdefault(item.group_index, []).append(item.response.grade.total)
        rec = {'unit': k, 'round': unit['round'], 'kind': unit['kind'], 'arm': self.arm, 'grouping': planned.plan.grouping, 'rollout_origin': origin,
               'bundle_sha256': block.sha256, 'rollout_policy_sha256': block.policy_sha256, 'policy_sha_before': policy_before,
               'policy_sha_after': self.backend.policy_sha(), 'adam_digest_before': adam_before, 'adam_digest_after': self.backend.adam_digest(),
               'rng_digest_after': self.backend.rng_digest(), 'updated': updated, 'update_decision': decision, 'effective_groups': planned.admitted_groups,
               'admitted_responses': len(planned.admitted_response_ids), 'responses': len(block.responses),
               'invalid_format_responses': sum(g.format != 1 for g in grades), 'correct_responses': sum(g.raw_accuracy == 1 for g in grades),
               'zero_variance_groups': sum(1 for v in groups.values() if max(v) - min(v) <= 1e-12),
               'gradient_l2': float(evidence.get('gradient_l2', 0.)), 'weighted_loss': float(evidence.get('weighted_loss', 0.)),
               'counters_delta': delta, 'counters_after': used, 'prev_receipt_sha256': self.last_receipt_sha}
        rec['receipt_sha256'] = identity({kk: v for kk, v in rec.items() if kk != 'receipt_sha256'})
        pending = Path(tempfile.mkdtemp(prefix=f'.pending-{k:04d}-', dir=self.output))
        files = list(self.backend.save_checkpoint(pending))
        (pending / 'own_old_PRIVATE.json').write_text(canonical({'bundle_sha256': block.sha256, 'old': own_old}) + '\n')
        (pending / 'gradient_evidence_PRIVATE.json').write_text(canonical(evidence) + '\n')
        files.extend(('own_old_PRIVATE.json', 'gradient_evidence_PRIVATE.json'))
        rec['files_sha256'] = {name: shared.file_sha256(pending / name) for name in files}
        rec['receipt_sha256'] = identity({kk: v for kk, v in rec.items() if kk != 'receipt_sha256'})
        (pending / 'bundle_PRIVATE.json').write_text(canonical(block.raw) + '\n')
        (pending / 'receipt_PRIVATE.json').write_text(canonical(rec) + '\n')
        for name in ('bundle_PRIVATE.json', 'receipt_PRIVATE.json', *files):
            with (pending / name).open('rb') as handle:
                os.fsync(handle.fileno())
        os.rename(pending, self.output / f'unit_{k:04d}')            # atomic commit point
        shared.sync_dir(self.output)
        self.committed.append(rec)
        self.last_receipt_sha = rec['receipt_sha256']
        shared.replace_atomic(self.output / 'cursor.json', self.cursor())
        return rec

    def safe_summary(self):
        rs = self.committed
        return {'status': 'ARM_COMPLETE' if len(rs) == len(self.units) else 'ARM_PARTIAL', 'arm': self.arm, 'units_committed': len(rs), 'units_planned': len(self.units),
                'optimizer_updates': sum(bool(r['updated']) for r in rs), 'groups_effective': sum(r['effective_groups'] for r in rs),
                'responses': sum(r['responses'] for r in rs), 'invalid_format_responses': sum(r['invalid_format_responses'] for r in rs),
                'zero_variance_groups': sum(r['zero_variance_groups'] for r in rs), 'common_rollout_units': sum(r['rollout_origin'] == 'COMMON_PARENT' for r in rs),
                'own_policy_units': sum(r['rollout_origin'] == 'OWN_POLICY' for r in rs), 'counters': self.counters.snapshot(), 'science_claim': False}
