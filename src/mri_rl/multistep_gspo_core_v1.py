"""LIMITED MULTISTEP real on-policy Vero-style GSPO A/B: backend-neutral CPU core. IMPLEMENTED_CPU_NOT_NATIVE_QUALIFIED.

No MLX, model load, generation or optimizer here; a backend object supplies them (CPU fake in tests, a future reviewed native
adapter). Extends the one-step shared-rollout core (same Bundle/plan/weight/gate/loss math, reused not copied) to a finite
sequence of UNITS taken from the paired-round exposure plan:  SEQ_PAIR (F4+T4, 8 responses, 1 update) then DALLAS_BLOCK
(two unchanged K4 groups, 8 responses, 1 update). Per admitted response weight is exactly 1/8 in BOTH arms and both block
kinds; A vs B differs only in how the sequence block's eight responses are grouped.

Policy ownership: the ONLY shared rollout is unit 0 (one F4+T4 generation from the common parent, consumed by both arms).
Every later unit is generated by the arm's OWN current policy, scored for its own old logps, differentiated and updated into
its own Adam/RNG line; a rollout whose policy identity differs from the arm's current policy is rejected (cross-arm/stale).
Nothing is resampled: invalid/zero-variance groups are kept and counted; an unfinished unit is a hard stop whose full reserved
cost is charged if a human abandons it. Atomic per-unit checkpoint (adapter+Adam+RNG), receipt hash chain, cursor.
"""
